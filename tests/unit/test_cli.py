"""Tests for atlagen CLI, config loader, and schema inspect helpers."""

from __future__ import annotations

import io
import textwrap
from pathlib import Path

import pytest

from atlagen.cli import main
from atlagen.config import ConfigError, build_parser, load_pyproject_settings, resolve_config
from atlagen.inspect import InspectError, load_schema_json

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures" / "atlas" / "postgres_users.json"


def test_resolve_config_merges_pyproject(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(
        textwrap.dedent(
            """\
            [tool.atlagen]
            dialect = "sqlite"
            out = "generated"
            schema = "schema.json"
            frozen = false
            """
        ),
        encoding="utf-8",
    )
    monkeypatch.chdir(tmp_path)
    parser = build_parser()
    args = parser.parse_args(["generate"])
    config = resolve_config(args, pyproject_settings=load_pyproject_settings())
    assert config.dialect == "sqlite"
    assert config.out == Path("generated")
    assert config.schema == "schema.json"
    assert config.frozen is False


def test_resolve_config_cli_overrides_pyproject() -> None:
    parser = build_parser()
    args = parser.parse_args(
        [
            "generate",
            "--dialect",
            "postgres",
            "--out",
            "out",
            "--schema",
            "-",
            "--frozen",
        ]
    )
    config = resolve_config(
        args,
        pyproject_settings={"dialect": "mysql", "out": "other", "frozen": False},
    )
    assert config.dialect == "postgres"
    assert config.out == Path("out")
    assert config.schema == "-"
    assert config.frozen is True


def test_resolve_config_requires_dialect_and_out() -> None:
    parser = build_parser()
    args = parser.parse_args(["generate", "--schema", "-"])
    with pytest.raises(ConfigError, match="dialect"):
        resolve_config(args, pyproject_settings={})


def test_resolve_config_rejects_non_boolean_frozen() -> None:
    parser = build_parser()
    args = parser.parse_args(["generate", "--dialect", "sqlite", "--out", "out"])
    with pytest.raises(ConfigError, match="frozen"):
        resolve_config(args, pyproject_settings={"frozen": "false"})


def test_load_schema_json_from_file() -> None:
    text = load_schema_json(str(FIXTURE))
    assert '"users"' in text


def test_load_schema_json_from_stdin() -> None:
    text = load_schema_json("-", stdin=io.StringIO(FIXTURE.read_text(encoding="utf-8")))
    assert "schemas" in text


def test_load_schema_json_missing_file(tmp_path: Path) -> None:
    with pytest.raises(InspectError, match="not found"):
        load_schema_json(str(tmp_path / "missing.json"))


def test_generate_and_check_roundtrip(tmp_path: Path) -> None:
    out = tmp_path / "generated"
    schema = str(FIXTURE)
    assert (
        main(
            [
                "generate",
                "--dialect",
                "postgres",
                "--schema",
                schema,
                "--out",
                str(out),
            ]
        )
        == 0
    )
    assert (out / "__init__.py").is_file()
    content = (out / "__init__.py").read_text(encoding="utf-8")
    assert "Code generated by atlagen" in content
    assert "users" in content

    assert (
        main(
            [
                "check",
                "--dialect",
                "postgres",
                "--schema",
                schema,
                "--out",
                str(out),
            ]
        )
        == 0
    )

    (out / "__init__.py").write_text("# drifted\n", encoding="utf-8")
    assert (
        main(
            [
                "check",
                "--dialect",
                "postgres",
                "--schema",
                schema,
                "--out",
                str(out),
            ]
        )
        == 1
    )


def test_generate_from_stdin_pipe(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    out = tmp_path / "generated"
    monkeypatch.setattr(
        "sys.stdin",
        io.StringIO(FIXTURE.read_text(encoding="utf-8")),
    )
    assert (
        main(
            [
                "generate",
                "--dialect",
                "postgres",
                "--schema",
                "-",
                "--out",
                str(out),
            ]
        )
        == 0
    )
    assert (out / "__init__.py").is_file()
