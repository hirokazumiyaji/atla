"""Code emitters for atlagen (expanded in Issue #9)."""

from __future__ import annotations

from atlagen.ir import SchemaIR


def generate_files(schema: SchemaIR, *, frozen: bool = True) -> dict[str, str]:
    """Return ``relative_path -> file contents`` for the mapped schema.

    Full ``enums.py`` / ``models.py`` / ``query.py`` / ``client.py`` emission is
    implemented in a later phase. Until then, write a stable stub that still lets
    ``generate`` / ``check`` exercise the CLI pipeline end-to-end.
    """
    _ = frozen
    tables = ", ".join(table.name for table in schema.tables) or "(none)"
    enums = ", ".join(enum.name for enum in schema.enums) or "(none)"
    content = (
        "# Code generated by atlagen. DO NOT EDIT.\n"
        f"# schema={schema.name!r} dialect={schema.dialect!r} frozen={frozen!r}\n"
        f"# tables={tables}\n"
        f"# enums={enums}\n"
        "\n"
        f"__schema_name__ = {schema.name!r}\n"
        f"__dialect__ = {schema.dialect!r}\n"
    )
    return {"__init__.py": content}
