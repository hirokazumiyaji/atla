"""Code emitters for atlagen-generated packages."""

from __future__ import annotations

from atlagen.emitter.client import emit_client
from atlagen.emitter.enums import emit_enums
from atlagen.emitter.models import emit_models
from atlagen.emitter.query import emit_query
from atlagen.ir import SchemaIR

_HEADER = "# Code generated by atlagen. DO NOT EDIT.\n"


def generate_files(schema: SchemaIR, *, frozen: bool = True) -> dict[str, str]:
    """Return ``relative_path -> file contents`` for the mapped schema."""
    files = {
        "enums.py": _HEADER + emit_enums(schema),
        "models.py": _HEADER + emit_models(schema, frozen=frozen),
        "query.py": _HEADER + emit_query(schema),
        "client.py": _HEADER + emit_client(schema),
    }
    exports = [
        "AtlaClient",
        *[enum.class_name for enum in schema.enums],
        *[f"{table.model_name}Record" for table in schema.tables],
        *[table.model_name for table in schema.tables],
    ]
    init_lines = [
        "from __future__ import annotations",
        "",
        "from .client import AtlaClient",
    ]
    if schema.enums:
        init_lines.append(
            "from .enums import " + ", ".join(enum.class_name for enum in schema.enums)
        )
    if schema.tables:
        init_lines.append(
            "from .models import "
            + ", ".join(f"{table.model_name}, {table.model_name}Record" for table in schema.tables)
        )
    init_lines.extend(
        [
            "",
            "__all__ = [",
            *[f"    {name!r}," for name in exports],
            "]",
            "",
        ]
    )
    files["__init__.py"] = _HEADER + "\n".join(init_lines)
    return files
